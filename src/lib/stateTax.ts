function prog(taxable: number, br: Br): number {
  let tax = 0;
  for (let i = 0; i < br.length; i++) {
    const lo = br[i][0];
    const rate = br[i][1];
    const hi = i + 1 < br.length ? br[i + 1][0] : Infinity;
    if (taxable <= lo) break;
    tax += (Math.min(taxable, hi) - lo) * rate;
  }
  return tax;
}

function federalSingle(wages: number): number {
  const taxable = Math.max(0, wages - STANDARD_DEDUCTION.single);
  let t = 0;
  for (const b of FEDERAL_BRACKETS_SINGLE) {
    if (taxable <= b.min) break;
    t += (Math.min(taxable, b.max) - b.min) * b.rate;
  }
  return t;
}

export function stateIncomeTax(code: string, wages: number, filing: StateFiling = 'single', fedTaxPaid?: number): number {
  const c = code.toLowerCase();
  const r = R[c];
  if (!r) return 0;
  const i = filing === 'married' ? 1 : 0;
  let sd = r.sd ? r.sd[i] : 0;
  let pe = r.pe ? r.pe[i] : 0;
  let cr = r.cr ? r.cr[i] : 0;
  const agi = wages;
  if (c === 'al') {
    sd = i === 0
      ? (agi <= 25499 ? 3000 : Math.max(2500, 3000 - 25 * Math.ceil((agi - 25499) / 500)))
      : (agi <= 25999 ? 8500 : Math.max(5000, 8500 - 175 * Math.ceil((agi - 25999) / 500)));
  }
  if (c === 'oh') pe = (agi <= 40000 ? 2400 : agi <= 80000 ? 2150 : agi < 500000 ? 1900 : 0) * (i ? 2 : 1);
  if (c === 'ut') cr = Math.max(0, cr - 0.013 * Math.max(0, agi - (i ? 36426 : 18213)));
  if (c === 'wi') {
    const start = i ? 29039 : 20119;
    const end = i ? 159690 : 136453;
    sd = sd * Math.max(0, 1 - Math.max(0, agi - start) / (end - start));
  }
  if (c === 'ct') pe = Math.max(0, pe - Math.max(0, agi - (i ? 48000 : 30000)));
  if (c === 'md') {
    const start = i ? 150000 : 100000;
    pe = pe * Math.min(1, Math.max(0, 1 - (agi - start) / 50000));
  }
  if (c === 'or' && agi > (i ? 200000 : 100000)) cr = 0;
  let taxable = Math.max(0, wages - sd - pe);
  if (c === 'al') taxable = Math.max(0, taxable - (fedTaxPaid !== undefined ? fedTaxPaid : federalSingle(wages)));
  let tax = prog(taxable, i ? r.m : r.s); if (c === 'ar' && taxable > 94700) tax = prog(taxable, [[0,0.02],[4700,0.037]]) - (taxable > 97600 ? 0 : 290 - 10 * Math.floor((taxable - 94701) / 100));
  if (c === 'ca') tax += Math.max(0, taxable - 1000000) * 0.01;
  return Math.max(0, tax - cr);
}

// Employee-paid state payroll programs (SDI / paid leave / long-term care) that are verified; others are not included.
export function statePayrollTax(code: string, wages: number): number {
  switch (code.toLowerCase()) {
    case 'ca': return wages * 0.013;
    case 'wa': return wages * 0.0058;
    case 'ma': return Math.min(wages, 184500) * 0.0046;
    case 'ny': return Math.min(31.2, wages * 0.005);
    default: return 0;
  }
}
